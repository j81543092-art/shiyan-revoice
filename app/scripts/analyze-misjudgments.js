/**
 * 误判明细 —— 看清 7 对误判分别是什么原因，判断「能否修」与「该不该修」
 *
 * 目的：不满足于「83.3% 准确率」这个数字，而是确认
 *   · 哪些是算法可改进的（真缺陷）
 *   · 哪些是标注本身有争议的（度量噪声）
 *   · 哪些是本质上需要语义理解、规则做不到的（应交给 L2 大模型）
 */

import { similarity as sim, injectNormalize, normalizeReady } from '../server/domain/scoring.js';
import { normalizeClue } from '../server/domain/normalize.js';
injectNormalize({ normalizeClue });

const SAME = [
  ['我左腿麻', '我的左腿发麻'], ['我头疼', '头很疼'], ['我想喝水', '我想喝点水'],
  ['我饿了，想吃饭', '我要吃饭'], ['我该几点吃药？', '什么时候吃药'],
  ['我困了，想睡觉', '想睡觉'], ['我要上厕所，很急', '我急着要上厕所'],
  ['我想看戏曲频道', '我想看电视里的戏曲'], ['我想儿子了', '我想我儿子了'],
  ['帮我给闺女打电话', '我想给闺女打电话'], ['我想上厕所', '我要去厕所'],
  ['我有点头晕', '头有点晕'], ['我饿了，想吃饭，再喝点水', '我想吃晚饭，再喝点水'],
  ['我要吃药，帮我倒点水', '我要吃药，喝点水'], ['我头疼，有点难受', '我头疼'],
  ['我想坐轮椅下楼晒太阳', '我想下楼晒会儿太阳'], ['我左腿麻', '左腿麻，有点不舒服'],
  ['我想跟小王视频', '叫王姐过来一下'], ['我想看电视里的戏曲', '帮我打开电视看戏曲'],
  ['我饿了，想吃晚饭', '我想吃晚饭，再喝点水'], ['我该吃药了', '我要吃药，喝点水'],
  ['我左腿发麻', '左腿麻，有点不舒服'],
];

const DIFF = [
  ['我想喝水', '我想吃饭'], ['我想睡觉', '我想关灯'], ['我头疼', '我腿疼'],
  ['我要上厕所', '我要吃药'], ['我想看电视', '我想看戏曲频道'],
  ['我想喝水', '我不想喝水'], ['我有点疼', '我疼得很厉害'],
  ['我要睡觉', '我想出门'], ['我饿了', '我渴了'], ['叫小王来', '叫小李来'],
  ['我想喝水', '我要上厕所'], ['我头疼', '我头晕'], ['我有点烦', '别烦我'],
  ['我想一个人待会儿', '我想儿子了'], ['我想睡觉', '我想关灯睡觉'],
  ['我想去厕所，然后换', '我想去厕所'], ['我想看电视', '我想下楼晒太阳'],
  ['我要吃药', '我要睡觉'],
];

const T = 0.35;

console.log('归一化就绪:', JSON.stringify(normalizeReady()), '\n');
console.log('═'.repeat(72));
console.log(`阈值 ${T} 下的全部误判`);
console.log('═'.repeat(72));

console.log('\n【假阴性】语义相同，但被判为不同（会让评测漏判）\n');
for (const [a, b] of SAME) {
  const s = sim(a, b);
  if (s < T) {
    console.log(`  ${s.toFixed(4)}  「${a}」vs「${b}」`);
    const ca = normalizeClue(a), cb = normalizeClue(b);
    console.log(`           概念 A=[${ca.join(',')}]  B=[${cb.join(',')}]`);
  }
}

console.log('\n【假阳性】语义不同，但被判为相同（会让去重误杀）\n');
for (const [a, b] of DIFF) {
  const s = sim(a, b);
  if (s >= T) {
    console.log(`  ${s.toFixed(4)}  「${a}」vs「${b}」`);
    const ca = normalizeClue(a), cb = normalizeClue(b);
    console.log(`           概念 A=[${ca.join(',')}]  B=[${cb.join(',')}]`);
  }
}

console.log('\n' + '═'.repeat(72));
console.log('分类判定');
console.log('═'.repeat(72));
console.log(`
  可修（算法层面）：
    · 概念集合为空导致退化为字面比较 → 扩大词表覆盖
    · 短句只有 1 个概念时，概念 Jaccard 过于极端

  度量噪声（标注有争议）：
    · 「我想睡觉」vs「我想关灯睡觉」—— 一条是纯意图，一条含动作，
      按 R1「候选必须有区分度」应区分；但若患者只是想说"要睡了"，
      两者可视为同一意图。**取决于用例定义，不是算法对错。**

  需 L2 大模型（规则本质做不到）：
    · 「叫小王来」vs「叫小李来」—— 人名差异需要常识才知道是不同人
    · 「我想跟小王视频」vs「叫王姐过来一下」—— 同一人不同称呼
`);
